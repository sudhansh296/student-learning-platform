export function getTechnologyBySlug(slug: string): Technology | undefined {
  return technologies.find(t => t.slug === slug);
}

export function getTopicBySlug(techSlug: string, topicSlug: string) {
  const tech = getTechnologyBySlug(techSlug);
  return tech?.topics.find(t => t.slug === topicSlug);
}

export function getTechnologiesByCategory(category: string): Technology[] {
  return technologies.filter(t => t.category === category || t.subcategory?.toLowerCase() === category.toLowerCase());
}

export function getPopularTechnologies(): Technology[] {
  return technologies.filter(t => t.isPopular);
}

export function searchTechnologies(query: string) {
  const q = query.toLowerCase();
  const results: Array<{ type: string; title: string; description: string; slug: string; technologySlug?: string; category: string }> = [];

  technologies.forEach(tech => {
    if (tech.name.toLowerCase().includes(q) || tech.description.toLowerCase().includes(q)) {
      results.push({
        type: 'technology',
        title: tech.name,
        description: tech.description,
        slug: tech.slug,
        category: tech.subcategory || tech.category
      });
    }
    tech.topics.forEach(topic => {
      if (topic.title.toLowerCase().includes(q) || topic.description.toLowerCase().includes(q) || topic.tags?.some(t => t.includes(q))) {
        results.push({
          type: 'topic',
          title: `${tech.name} → ${topic.title}`,
          description: topic.description,
          slug: topic.slug,
          technologySlug: tech.slug,
          category: tech.subcategory || tech.category
        });
      }
    });
  });

  return results.slice(0, 10);
}
